# Порядок ротации: соседние типы максимально разные
_ROTATION_POOL = ["expert", "checklist", "myth", "question", "compare", "mistake", "transformation"]

_state = {"last": None, "count": {}}


def pick_post_type() -> str:
    """Выбирает тип поста: не повторяет предыдущий, ведёт статистику."""
    candidates = [t for t in _ROTATION_POOL if t != _state["last"]]
    # 60% — наименее использованные, 40% — случайные (живость)
    if random.random() < 0.6 and len(candidates) > 1:
        min_used = min(_state["count"].get(t, 0) for t in candidates)
        least = [t for t in candidates if _state["count"].get(t, 0) == min_used]
        chosen = random.choice(least)
    else:
        chosen = random.choice(candidates)
    _state["last"] = chosen
    _state["count"][chosen] = _state["count"].get(chosen, 0) + 1
    return chosen


def get_type_block(post_type: Optional[str] = None) -> str:
    """Возвращает блок промпта для типа поста (или выбирает сам)."""
    t = post_type or pick_post_type()
    block = POST_TYPES.get(t, POST_TYPES["expert"])
    logger.info(f"Post type selected: {t}")
    return block


def last_post_type() -> str:
    """Тип, выбранный последним вызовом get_type_block()/pick_post_type().

    Нужен для типовых проверок структурной целостности (_is_structurally_incomplete):
    сравнение без «Вариант 1/2», миф без «Правда:» и т.п.
    """
    return _state.get("last") or "expert"

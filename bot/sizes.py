_CLOSING = (
    "💡 Все эти размеры я учитываю на бесплатном замере — "
    "ваша мебель подгоняется под рост и привычки, а не наоборот 📐"
)

# ─── Клавиатуры ──────────────────────────────────────────────────────────────


def _rooms_keyboard() -> InlineKeyboardMarkup:
    rows = [
        [InlineKeyboardButton(text=f"{emoji} {name}", callback_data=f"sz:{key}")]
        for key, (name, emoji) in SIZE_ROOMS.items()
    ]
    rows.append([
        InlineKeyboardButton(text="📐 Бесплатный замер", callback_data="measure:start"),
        InlineKeyboardButton(text="🧮 Калькулятор", callback_data="calc:restart"),
    ])
    return InlineKeyboardMarkup(inline_keyboard=rows)


def _result_keyboard() -> InlineKeyboardMarkup:
    return InlineKeyboardMarkup(inline_keyboard=[
        [InlineKeyboardButton(text="🔄 Другая комната", callback_data="sz:menu")],
        [InlineKeyboardButton(text="📐 Бесплатный замер", callback_data="measure:start"),
         InlineKeyboardButton(text="🧮 Калькулятор", callback_data="calc:restart")],
        [InlineKeyboardButton(text="⚠️ 5 ошибок при заказе", callback_data="mst:menu"),
         InlineKeyboardButton(text="🗃 Идеи хранения", callback_data="storage:menu")],
    ])


# ─── Тексты ──────────────────────────────────────────────────────────────────

_INTRO = (
    "📏 <b>Стандартные размеры и эргономика</b>\n\n"
    "Таблицы из практики проектирования. Выберите комнату — покажу, "
    "какие размеры считаются эталоном и почему:"
)


def _room_text(room: str) -> str:
    name, emoji = SIZE_ROOMS[room]
    lines = [f"📏 <b>Стандартные размеры — {name}</b> {emoji}\n"]
    for title, why in SIZE_STANDARDS[room]:
        lines.append(f"<b>📐 {title}</b>")
        lines.append(f"{why}\n")
    lines.append(_CLOSING)
    return "\n".join(lines)


# ─── Хендлеры ────────────────────────────────────────────────────────────────


@sizes_router.message(Command("sizes"))
async def cmd_sizes(message: Message):
    """Меню комнат — личка и группы."""
    await message.reply(_INTRO, reply_markup=_rooms_keyboard())


@sizes_router.callback_query(F.data == "sz:menu")
async def cb_sizes_menu(cb: CallbackQuery):
    try:
        await cb.message.edit_text(_INTRO, reply_markup=_rooms_keyboard())
    except Exception:
        pass
    await cb.answer()


@sizes_router.callback_query(F.data.startswith("sz:"))
async def cb_sizes_show(cb: CallbackQuery):
    """Показ стандартов по комнате: callback_data = sz:<room> (stateless)."""
    try:
        room = cb.data.split(":")[1]
        if room not in SIZE_STANDARDS:
            await cb.answer("Такой комнаты пока нет 🙂", show_alert=False)
            return
        text = _room_text(room)
        try:
            await cb.message.edit_text(text, reply_markup=_result_keyboard())
        except Exception:
            await cb.message.reply(text, reply_markup=_result_keyboard())
        await cb.answer()
    except Exception as e:
        logger.warning(f"sizes callback failed: {e}")
        try:
            await cb.answer("Ошибка, попробуйте ещё раз 🙂", show_alert=False)
        except Exception:
            pass

def format_product_for_context(product: Dict) -> str:
    """Форматирует товар для вставки в AI-контекст."""
    name = product.get("name", "")
    desc = product.get("desc", "")
    sizes = product.get("sizes", "")
    price = product.get("from_price", "")
    return (
        f"«{name}» — {desc}; {sizes}; {price}. "
        f"Подробности и заказ: {_SITE} (упомяни естественно, если собеседник ищет похожее)"
    )


def format_post_for_context(post: Dict) -> str:
    """Форматирует пост для вставки в AI-контекст."""
    title = post.get("title", "")
    text = post.get("text", "")
    return f"«{title}» — {text} (ссылка: {_SITE}, можешь поделиться если к месту)"


def catalog_summary(max_items: int = 6) -> str:
    """Краткая сводка каталога (для промптов канала/админа)."""
    lines = []
    for p in _PRODUCTS[:max_items]:
        lines.append(f"• {p['name']} ({p['from_price']})")
    return "\n".join(lines)

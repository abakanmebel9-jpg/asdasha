_last_shown: List[int] = []


def get_reviews(n: int = 3) -> List[Dict]:
    """Возвращает n отзывов без повторов с прошлых показов (ротация)."""
    global _last_shown
    if len(_REVIEWS) <= n:
        return list(_REVIEWS)
    pool = [i for i in range(len(_REVIEWS)) if i not in _last_shown]
    if len(pool) < n:
        pool = list(range(len(_REVIEWS)))
        _last_shown = []
    chosen = random.sample(pool, n)
    _last_shown = chosen[-n:] if len(chosen) >= n else chosen
    return [_REVIEWS[i] for i in chosen]


def format_reviews(n: int = 3) -> str:
    """Форматирует отзывы для отправки в чат."""
    items = get_reviews(n)
    lines = ["⭐ <b>Отзывы наших клиентов</b>\n"]
    for r in items:
        lines.append(f"💬 <b>{r['name']}</b> — {r['project']}:")
        lines.append(f"«{r['text']}»\n")
    lines.append("🛋 Кухни, шкафы-купе, гардеробные, прихожие — на заказ по вашим размерам.")
    return "\n".join(lines)

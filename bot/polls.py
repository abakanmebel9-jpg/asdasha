_bank_order = {"i": 0, "order": []}


def _shuffle():
    _bank_order["order"] = random.sample(range(len(POLL_BANK)), len(POLL_BANK))
    _bank_order["i"] = 0


def next_poll():
    """Следующий опрос без повторов, пока не исчерпан банк (потом перемешать)."""
    if not _bank_order["order"]:
        _shuffle()
    idx = _bank_order["order"][_bank_order["i"] % len(POLL_BANK)]
    _bank_order["i"] += 1
    if _bank_order["i"] >= len(POLL_BANK):
        _shuffle()
    q, opts, correct, expl = POLL_BANK[idx]
    return {"question": q, "options": opts, "correct": correct, "explanation": expl}


async def maybe_send_poll(bot, channel_id: int) -> bool:
    """Отправляет опрос, если с прошлого прошло ≥4 ч и повезло с шансом.

    Дедуп: вопрос, отправленный раньше (в т.ч. до рестарта), пропускается.
    Любая ошибка — тихо логируется, посты канала не затрагиваются.
    """
    from bot import database as db

    last = await db.get_posted_ts(_LAST_KEY)
    now = int(time.time())
    if last and (now - last) < _MIN_GAP_SEC:
        return False
    if random.random() > _SEND_CHANCE:
        return False

    for _ in range(len(POLL_BANK)):  # ищем вопрос, которого ещё не было
        poll = next_poll()
        fp = _fingerprint(poll["question"])
        if not await db.is_news_posted(_PREFIX + fp):
            break
    else:
        # Банк исчерпан — чистим дедуп (сохраняя метку времени последнего опроса),
        # цикл начнётся заново: полный круг без повторов
        cleared = await db.delete_posted_keys(_PREFIX, exclude=_LAST_KEY)
        logger.info(f"Polls: bank exhausted — reset {cleared} dedup keys, cycle restarts")
        return False

    try:
        # Есть правильный ответ → квиз «Проверь себя» с пояснением; иначе обычный опрос
        is_quiz = poll["correct"] is not None
        if is_quiz:
            await bot.send_poll(
                chat_id=channel_id,
                question="🧠 " + poll["question"],
                options=poll["options"],
                type="quiz",
                correct_option_id=poll["correct"],
                explanation=(poll["explanation"] or "")[:200],
                is_anonymous=False,
            )
        else:
            await bot.send_poll(
                chat_id=channel_id,
                question="📊 " + poll["question"],
                options=poll["options"],
                is_anonymous=False,
                allows_multiple_answers=False,
            )
        await db.mark_news_posted(_LAST_KEY, "poll-timestamp")
        await db.mark_news_posted(_PREFIX + fp, poll["question"])
        logger.info(f"Poll sent ({'quiz' if is_quiz else 'regular'}): {poll['question'][:50]}")
        return True
    except Exception as e:
        logger.warning(f"send_poll failed: {e}")
        return False


def _fingerprint(question: str) -> str:
    """Компактный отпечаток вопроса для дедупа (буквы+цифры, нижний регистр)."""
    import re
    return re.sub(r"[^a-zа-я0-9]+", "", (question or "").lower())[:80]

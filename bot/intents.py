# Каждому интенту — своя клавиатура не нужна: одна общая с главным действием
from aiogram.types import InlineKeyboardButton, InlineKeyboardMarkup


def _intent_keyboard() -> InlineKeyboardMarkup:
    return InlineKeyboardMarkup(inline_keyboard=[
        [InlineKeyboardButton(text="📐 Бесплатный замер", callback_data="measure:start"),
         InlineKeyboardButton(text="🧮 Посчитать цену", callback_data="calc:restart")],
        [InlineKeyboardButton(text="📞 Позвонить", url=f"tel:+{_PHONE_DIGITS}"),
         InlineKeyboardButton(text="💬 WhatsApp", url=f"https://wa.me/{_PHONE_DIGITS}")],
    ])


def match_intent(text: str):
    """Возвращает (name, answer_text, with_kb) первого совпавшего интента или None.

    Ловит основы слов (склонения), сработает только на «коротких» сообщениях —
    развёрнутый рассказ клиент уходит в обычный AI-диалог.
    """
    t = (text or "").strip()
    if not t or len(t) > 140 or t.startswith("/"):
        return None
    for name, (pattern, answer, with_kb) in _INTENT_RULES:
        if re.search(pattern, t):
            return (name, answer, with_kb)
    return None


async def try_instant_reply(bot, chat_id: int, user_id: int, text: str):
    """Пробует ответить мгновенным интентом. Возвращает текст ответа или None."""
    m = match_intent(text)
    if not m:
        return None
    name, answer, with_kb = m
    now = time.time()
    if now - _last_intent_ts.get(user_id, 0) < _COOLDOWN_SEC:
        return None  # недавно уже отвечали мгновенно — дальше живой диалог
    _last_intent_ts[user_id] = now
    try:
        if with_kb:
            await bot.send_message(chat_id, answer, reply_markup=_intent_keyboard())
        else:
            await bot.send_message(chat_id, answer)
        logger.info(f"Instant intent '{name}' → user {user_id}: {text[:50]}")
        return answer
    except Exception as e:
        logger.warning(f"Instant intent '{name}' send failed: {e}")
        return None

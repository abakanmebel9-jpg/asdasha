def weekday_theme() -> Tuple[str, str]:
    """Тематический фокус дня недели (Абакан = UTC+7, как таймзона постов).

    Возвращает (метка, блок-инструкция). Блок — мягкий: не ломает тип поста
    и новость, лишь задаёт угол подачи.
    """
    # Красноярск = UTC+7 (согласовано с шедулером бота)
    tz = timezone(timedelta(hours=7))
    day = datetime.now(tz).weekday()
    name, block, _kw = _WEEKDAY_THEMES[day]
    return name, block


def weekday_keywords() -> tuple:
    """Ключевые слова тем, попадающих в фокус сегодняшнего дня."""
    tz = timezone(timedelta(hours=7))
    day = datetime.now(tz).weekday()
    return _WEEKDAY_THEMES[day][2]


def topic_matches_weekday(topic: str) -> bool:
    """Подходит ли тема под фокус сегодняшнего дня (по ключевым словам)."""
    t = (topic or "").lower()
    kw = weekday_keywords()
    return any(k in t for k in kw)

"""
Даша Post Context — время суток и сезонность для постов канала.

Утренний пост ≠ вечернему: утром короткий совет, вечером вдохновение.
Плюс сезонные темы (осень — обновления к холодам, декабрь — подарки и заказы к НГ).
"""

import logging
from datetime import datetime, timezone, timedelta
from typing import Tuple

logger = logging.getLogger("dasha.post_context")

_MOSCOW_TZ = timezone(timedelta(hours=3))


def _now():
    return datetime.now(_MOSCOW_TZ)


def time_of_day_profile() -> Tuple[str, str]:
    """Возвращает (метка, блок-инструкция для промпта)."""
    h = _now().hour
    if 6 <= h < 11:
        return (
            "утро",
            "ВРЕМЯ: утро. Подача: короткий бодрый совет «с кофе» — конкретный, практичный, на один взгляд. "
            "Тон бодрый, без тяжёлых технических деталей, максимум одна цифра."
        )
    if 11 <= h < 17:
        return (
            "день",
            "ВРЕМЯ: день. Подача: рабочий экспертный разбор — можно с цифрами, размерами, сравнениями материалов. "
            "Аудитория обдумывает ремонт, дай пищи для решения."
        )
    if 17 <= h < 22:
        return (
            "вечер",
            "ВРЕМЯ: вечер. Подача: тёплая, расслабленная — вдохновение, идеи «мечты», истории из проектов. "
            "Больше эмоций и атмосферы, меньше технических подробностей."
        )
    return (
        "поздний вечер",
        "ВРЕМЯ: поздний вечер. Подача: спокойная, задумчивая, уютная. Лёгкая тема, мягкий тон, без агрессивной продажи."
    )



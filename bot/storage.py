# ─── Клавиатуры ──────────────────────────────────────────────────────────────


def _rooms_keyboard() -> InlineKeyboardMarkup:
    rows = [
        [InlineKeyboardButton(text=f"🗂 {name}", callback_data=f"storage:{key}:0")]
        for key, name in ROOMS.items()
    ]
    rows.append([
        InlineKeyboardButton(text="📐 Бесплатный замер", callback_data="measure:start"),
        InlineKeyboardButton(text="🧮 Калькулятор", callback_data="calc:restart"),
    ])
    return InlineKeyboardMarkup(inline_keyboard=rows)


def _solution_keyboard(room: str, idx: int) -> InlineKeyboardMarkup:
    total = len(SOLUTIONS.get(room, []))
    nxt = (idx + 1) % total if total else 0
    return InlineKeyboardMarkup(inline_keyboard=[
        [InlineKeyboardButton(text="💡 Ещё идея", callback_data=f"storage:{room}:{nxt}")],
        [InlineKeyboardButton(text="📐 Бесплатный замер", callback_data="measure:start"),
         InlineKeyboardButton(text="🧮 Калькулятор", callback_data="calc:restart")],
        [InlineKeyboardButton(text="⬅️ Другая комната", callback_data="storage:menu")],
    ])


def _solution_text(room: str, idx: int) -> str:
    title, text = SOLUTIONS[room][idx]
    total = len(SOLUTIONS[room])
    return (
        f"🗃 <b>Идеи хранения — {ROOMS[room]}</b>\n"
        f"({idx + 1} из {total})\n\n"
        f"🔹 <b>{title}</b>\n\n"
        f"{text}\n\n"
        f"Хочу такую систему под свои размеры — замерю и посчитаю бесплатно 📐"
    )


# ─── Хендлеры ─────────────────────────────────────────────────────────────────


@storage_router.message(Command("storage"))
async def cmd_storage(message: Message):
    """Меню комнат — личка и группы."""
    await message.reply(
        "🗃 <b>Идеи хранения от дизайнера</b>\n\n"
        "Выбирайте комнату — покажу конкретные решения, "
        "которые реально делаем в производстве:",
        reply_markup=_rooms_keyboard(),
    )


@storage_router.callback_query(F.data == "storage:menu")
async def cb_storage_menu(cb: CallbackQuery):
    try:
        await cb.message.edit_text(
            "🗃 <b>Идеи хранения от дизайнера</b>\n\n"
            "Выбирайте комнату — покажу конкретные решения, "
            "которые реально делаем в производстве:",
            reply_markup=_rooms_keyboard(),
        )
    except Exception:
        pass
    await cb.answer()


@storage_router.callback_query(F.data.startswith("storage:"))
async def cb_storage_show(cb: CallbackQuery):
    """Показ решения: callback_data = storage:<room>:<idx> (≤64 байт, stateless)."""
    try:
        _, room, idx_s = cb.data.split(":")
        idx = int(idx_s)
        if room not in SOLUTIONS or not (0 <= idx < len(SOLUTIONS[room])):
            await cb.answer("Такой идеи пока нет 🙂", show_alert=False)
            return
        try:
            await cb.message.edit_text(
                _solution_text(room, idx),
                reply_markup=_solution_keyboard(room, idx),
            )
        except Exception:
            # сообщение нельзя отредактировать (например, в некоторых группах) — шлём новое
            await cb.message.reply(
                _solution_text(room, idx),
                reply_markup=_solution_keyboard(room, idx),
            )
        await cb.answer()
    except Exception as e:
        logger.warning(f"storage callback failed: {e}")
        try:
            await cb.answer("Ошибка, попробуйте ещё раз 🙂", show_alert=False)
        except Exception:
            pass
